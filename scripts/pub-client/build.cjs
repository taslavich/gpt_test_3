'use strict';
const fs = require('node:fs'), path = require('node:path'), { transformSync } = require('esbuild');
const root = path.resolve(__dirname, '../../internal/services/pub');
const jobs = [
 ['sdk.prod.js', fs.readFileSync(path.join(root, 'sdk.js'), 'utf8')],
 ['runtime.prod.js', ['routing.js', 'adManager.js'].map(name => fs.readFileSync(path.join(root, name), 'utf8')).join('\n')]
];
for (const [name, source] of jobs) {
 // Identifier mangling is deliberately moderate: no property renaming, eval, packers or string decoding.
 const code = '/* Generated by scripts/pub-client/build.cjs; edit readable sources. */\n' + transformSync(source, { minify: true, target: ['es2021'], charset: 'utf8', legalComments: 'none' }).code;
 const target = path.join(root, name);
 if (process.argv.includes('--check')) { if (fs.readFileSync(target, 'utf8') !== code) throw new Error(name + ' is stale'); }
 else fs.writeFileSync(target, code);
 console.log((process.argv.includes('--check') ? 'CHECK ' : 'BUILD ') + name + ' ' + Buffer.byteLength(code) + ' bytes');
}
